#!/usr/bin/env python3
"""
Validate DDS source generated by codegen-dds (PF/LF only).

Usage:
    python validate-dds-source.py --type pf <file1> [file2 ...]
    python validate-dds-source.py --type lf <file1> [file2 ...]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PFILE_RE = re.compile(r"\bPFILE\(", re.IGNORECASE)


def is_skippable(line: str) -> bool:
    s = line.strip()
    if not s:
        return True
    if s.startswith("A*"):
        return True
    if s.startswith("*"):
        return True
    return False


def padded80(line: str) -> str:
    return line[:80].ljust(80)


def has_form_type_a_in_col6(line: str) -> bool:
    return len(line) >= 6 and line[5] == "A"


def spec_char_col17(line: str) -> str:
    return padded80(line)[16]


def validate_common(lines: list[str], path: Path) -> list[str]:
    errors: list[str] = []
    has_record = False

    for i, line in enumerate(lines, start=1):
        if is_skippable(line):
            continue
        if len(line) > 80:
            errors.append(f"{path}:{i}: DDS source line exceeds 80 columns")
        # Check column 6: DDS form type A must be at column 6 (5 leading spaces)
        if not has_form_type_a_in_col6(line):
            errors.append(f"{path}:{i}: DDS line must start with 'A' at column 6 (5 leading spaces)")
        if spec_char_col17(line).upper() == "R":
            has_record = True

    if not has_record:
        errors.append(f"{path}: missing DDS record format line (A ... R ...)")

    return errors


def validate_by_type(member_type: str, text: str, path: Path) -> list[str]:
    errors: list[str] = []

    if member_type == "pf":
        if PFILE_RE.search(text):
            errors.append(f"{path}: PF should not include PFILE keyword")
    elif member_type == "lf":
        if not PFILE_RE.search(text):
            errors.append(f"{path}: LF is missing PFILE keyword")

    return errors


def validate_file(member_type: str, path: Path) -> list[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception as ex:
        return [f"{path}: unable to read file ({ex})"]

    lines = text.splitlines()
    if not lines:
        return [f"{path}: file is empty"]

    errors = validate_common(lines, path)
    errors.extend(validate_by_type(member_type, text, path))
    return errors


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Validate DDS source members")
    parser.add_argument("--type", required=True, choices=["pf", "lf"], help="DDS member type")
    parser.add_argument("files", nargs="+", help="DDS source files to validate")
    args = parser.parse_args(argv[1:])

    all_errors: list[str] = []
    for raw in args.files:
        path = Path(raw)
        if not path.exists():
            all_errors.append(f"{path}: file does not exist")
            continue
        all_errors.extend(validate_file(args.type, path))

    if all_errors:
        for error in all_errors:
            print(f"ERROR: {error}")
        return 1

    print(f"OK: all {args.type.upper()} files passed DDS checks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
