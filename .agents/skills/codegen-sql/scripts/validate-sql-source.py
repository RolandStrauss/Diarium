#!/usr/bin/env python3
"""
Validate SQL source generated by codegen-sql.

Usage:
  python validate-sql-source.py --type sql <file1> [file2 ...]
  python validate-sql-source.py --type sqltable <file1> [file2 ...]
  python validate-sql-source.py --type sqlview <file1> [file2 ...]
  python validate-sql-source.py --type sqlproc <file1> [file2 ...]
  python validate-sql-source.py --type sqltrigger <file1> [file2 ...]
  python validate-sql-source.py --type sqlindex <file1> [file2 ...]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CREATE_TABLE_RE = re.compile(r"\bCREATE\s+(OR\s+REPLACE\s+)?TABLE\b", re.IGNORECASE)
CREATE_VIEW_RE = re.compile(r"\bCREATE\s+(OR\s+REPLACE\s+)?VIEW\b", re.IGNORECASE)
CREATE_PROC_RE = re.compile(r"\bCREATE\s+(OR\s+REPLACE\s+)?PROCEDURE\b", re.IGNORECASE)
CREATE_TRIGGER_RE = re.compile(r"\bCREATE\s+(OR\s+REPLACE\s+)?TRIGGER\b", re.IGNORECASE)
CREATE_INDEX_RE = re.compile(r"\bCREATE\s+(UNIQUE\s+)?INDEX\b", re.IGNORECASE)
SET_SCHEMA_RE = re.compile(r"\bSET\s+CURRENT\s+SCHEMA\b", re.IGNORECASE)
STOP_RE = re.compile(r"\bstop\s*;", re.IGNORECASE)
FOR_SYSTEM_NAME_RE = re.compile(r"\bFOR\s+SYSTEM\s+NAME\b", re.IGNORECASE)
PRIMARY_KEY_RE = re.compile(r"\bPRIMARY\s+KEY\b", re.IGNORECASE)
RECORD_STATUS_RE = re.compile(r"\bRECORDSTATUS\s+FOR\s+RCDSTS\b", re.IGNORECASE)
BEGINNING_TIME_RE = re.compile(r"\bBEGINNING_TIME\s+FOR\s+BEGTIM\b", re.IGNORECASE)
ENDING_TIME_RE = re.compile(r"\bENDING_TIME\s+FOR\s+ENDTIM\b", re.IGNORECASE)
TRANSACTION_START_RE = re.compile(r"\bTRANSACTION_START\s+FOR\s+TRXSTR\b", re.IGNORECASE)
PERIOD_SYSTEM_TIME_RE = re.compile(r"\bPERIOD\s+SYSTEM_TIME\s*\(\s*BEGINNING_TIME\s*,\s*ENDING_TIME\s*\)", re.IGNORECASE)
AUD_USER_RE = re.compile(r"\bAUD_USER\s+FOR\s+AUDUSR\b", re.IGNORECASE)
AUD_CHANGE_RE = re.compile(r"\bAUD_CHANGE\s+FOR\s+AUDCHG\b", re.IGNORECASE)
AUD_JOBNAME_RE = re.compile(r"\bAUD_JOBNAME\s+FOR\s+AUDJOB\b", re.IGNORECASE)
AUD_PGM_RE = re.compile(r"\bAUD_PGM\s+FOR\s+AUDPGM\b", re.IGNORECASE)
SELECT_RE = re.compile(r"\bSELECT\b", re.IGNORECASE)
BEGIN_RE = re.compile(r"\bBEGIN\b", re.IGNORECASE)
END_RE = re.compile(r"\bEND\s*;", re.IGNORECASE)
LANGUAGE_SQL_RE = re.compile(r"\bLANGUAGE\s+SQL\b", re.IGNORECASE)
FOR_EACH_ROW_RE = re.compile(r"\bFOR\s+EACH\s+ROW\b", re.IGNORECASE)
MODE_DB2SQL_RE = re.compile(r"\bMODE\s+DB2SQL\b", re.IGNORECASE)
ON_TABLE_RE = re.compile(r"\bON\s+[A-Z0-9_]+\b", re.IGNORECASE)
DESTRUCTIVE_SQL_RE = re.compile(r"\b(DROP|TRUNCATE)\b", re.IGNORECASE)

SQLTABLE_REQUIRED_PATTERNS = [
    (RECORD_STATUS_RE, "RecordStatus for rcdsts"),
    (BEGINNING_TIME_RE, "beginning_time for begtim"),
    (ENDING_TIME_RE, "ending_time for endtim"),
    (TRANSACTION_START_RE, "transaction_start for trxstr"),
    (PERIOD_SYSTEM_TIME_RE, "period system_time (beginning_time, ending_time)"),
    (AUD_USER_RE, "aud_user for audusr"),
    (AUD_CHANGE_RE, "aud_change for audchg"),
    (AUD_JOBNAME_RE, "aud_jobname for audjob"),
    (AUD_PGM_RE, "aud_pgm for audpgm"),
]


def validate_common(text: str, path: Path) -> list[str]:
    errors: list[str] = []

    if not text.strip():
        return [f"{path}: file is empty"]

    if ";" not in text:
        errors.append(f"{path}: SQL member must include statement terminators ';'")

    if not STOP_RE.search(text):
        errors.append(f"{path}: expected at least one 'stop;' delimiter for RUNSQLSTM safety")

    if DESTRUCTIVE_SQL_RE.search(text):
        errors.append(f"{path}: destructive SQL statements (DROP/TRUNCATE) are not allowed in default scaffolds")

    return errors


def validate_by_type(member_type: str, text: str, path: Path) -> list[str]:
    errors: list[str] = []

    if member_type == "sql":
        if not (SET_SCHEMA_RE.search(text) or SELECT_RE.search(text)):
            errors.append(f"{path}: generic SQL should include SET CURRENT SCHEMA or a query")
    elif member_type == "sqltable":
        if not CREATE_TABLE_RE.search(text):
            errors.append(f"{path}: sqltable must include CREATE TABLE")
        if not FOR_SYSTEM_NAME_RE.search(text):
            errors.append(f"{path}: sqltable should include FOR SYSTEM NAME")
        if not PRIMARY_KEY_RE.search(text):
            errors.append(f"{path}: sqltable should define a PRIMARY KEY")
        for pattern, column_label in SQLTABLE_REQUIRED_PATTERNS:
            matches = pattern.findall(text)
            if not matches:
                errors.append(
                    f"{path}: sqltable must include standard/audit column '{column_label}'"
                )
            elif len(matches) > 1:
                errors.append(
                    f"{path}: sqltable must not duplicate standard/audit column '{column_label}'"
                )
    elif member_type == "sqlview":
        if not CREATE_VIEW_RE.search(text):
            errors.append(f"{path}: sqlview must include CREATE VIEW")
        if not SELECT_RE.search(text):
            errors.append(f"{path}: sqlview must include a SELECT projection")
    elif member_type == "sqlproc":
        if not CREATE_PROC_RE.search(text):
            errors.append(f"{path}: sqlproc must include CREATE PROCEDURE")
        if not LANGUAGE_SQL_RE.search(text):
            errors.append(f"{path}: sqlproc should include LANGUAGE SQL")
        if not BEGIN_RE.search(text) or not END_RE.search(text):
            errors.append(f"{path}: sqlproc should include BEGIN ... END; block")
    elif member_type == "sqltrigger":
        if not CREATE_TRIGGER_RE.search(text):
            errors.append(f"{path}: sqltrigger must include CREATE TRIGGER")
        if not FOR_EACH_ROW_RE.search(text):
            errors.append(f"{path}: sqltrigger should include FOR EACH ROW")
        if not MODE_DB2SQL_RE.search(text):
            errors.append(f"{path}: sqltrigger should include MODE DB2SQL")
    elif member_type == "sqlindex":
        if not CREATE_INDEX_RE.search(text):
            errors.append(f"{path}: sqlindex must include CREATE INDEX")
        if not ON_TABLE_RE.search(text):
            errors.append(f"{path}: sqlindex should include ON <table>")

    return errors


def validate_file(member_type: str, path: Path) -> list[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception as ex:
        return [f"{path}: unable to read file ({ex})"]

    errors = validate_common(text, path)
    errors.extend(validate_by_type(member_type, text, path))
    return errors


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Validate IBM i SQL source members")
    parser.add_argument(
        "--type",
        required=True,
        choices=["sql", "sqltable", "sqlview", "sqlproc", "sqltrigger", "sqlindex"],
        help="SQL member type",
    )
    parser.add_argument("files", nargs="+", help="SQL source files to validate")
    args = parser.parse_args(argv[1:])

    all_errors: list[str] = []
    for raw in args.files:
        path = Path(raw)
        if not path.exists():
            all_errors.append(f"{path}: file does not exist")
            continue
        all_errors.extend(validate_file(args.type, path))

    if all_errors:
        for error in all_errors:
            print(f"ERROR: {error}")
        return 1

    print(f"OK: all {args.type.upper()} files passed SQL checks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
