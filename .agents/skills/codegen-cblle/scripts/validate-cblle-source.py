#!/usr/bin/env python3
"""
Validate COBOL source generated by codegen-cblle.

Usage:
  python validate-cblle-source.py --type cblle <file1> [file2 ...]
  python validate-cblle-source.py --type sqlcblle <file1> [file2 ...]
  python validate-cblle-source.py --type cpy <file1> [file2 ...]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

IDENT_RE = re.compile(r"^\s*IDENTIFICATION\s+DIVISION\.", re.IGNORECASE | re.MULTILINE)
PROGRAM_ID_RE = re.compile(r"^\s*PROGRAM-ID\s*\.\s*[A-Z0-9_\-]+\.", re.IGNORECASE | re.MULTILINE)
PROC_DIV_RE = re.compile(r"^\s*PROCEDURE\s+DIVISION\.", re.IGNORECASE | re.MULTILINE)
WORKING_STORAGE_RE = re.compile(r"^\s*WORKING-STORAGE\s+SECTION\.", re.IGNORECASE | re.MULTILINE)
GOBACK_RE = re.compile(r"\bGOBACK\b", re.IGNORECASE)
SQLCA_RE = re.compile(r"EXEC\s+SQL\s+INCLUDE\s+SQLCA\s+END-EXEC\.?", re.IGNORECASE)
EXEC_SQL_RE = re.compile(r"EXEC\s+SQL\b", re.IGNORECASE)
SQLSTATE_CHECK_RE = re.compile(r"(?:SQLSTATE\s*=\s*'00000'|WS-SQLSTATE\s*=\s*'00000')", re.IGNORECASE)
SQLSTATE_NO_DATA_RE = re.compile(r"(?:SQLSTATE\s*=\s*'02000'|WS-SQLSTATE\s*=\s*'02000')", re.IGNORECASE)
SQLSTATE_ERROR_BRANCH_RE = re.compile(r"\bWHEN\s+OTHER\b", re.IGNORECASE)
CREATE_TABLE_RE = re.compile(r"\bCREATE\s+(OR\s+REPLACE\s+)?TABLE\b", re.IGNORECASE)
RECORD_STATUS_RE = re.compile(r"\bRECORDSTATUS\s+FOR\s+RCDSTS\b", re.IGNORECASE)
BEGINNING_TIME_RE = re.compile(r"\bBEGINNING_TIME\s+FOR\s+BEGTIM\b", re.IGNORECASE)
ENDING_TIME_RE = re.compile(r"\bENDING_TIME\s+FOR\s+ENDTIM\b", re.IGNORECASE)
TRANSACTION_START_RE = re.compile(r"\bTRANSACTION_START\s+FOR\s+TRXSTR\b", re.IGNORECASE)
PERIOD_SYSTEM_TIME_RE = re.compile(r"\bPERIOD\s+SYSTEM_TIME\s*\(\s*BEGINNING_TIME\s*,\s*ENDING_TIME\s*\)", re.IGNORECASE)
AUD_USER_RE = re.compile(r"\bAUD_USER\s+FOR\s+AUDUSR\b", re.IGNORECASE)
AUD_CHANGE_RE = re.compile(r"\bAUD_CHANGE\s+FOR\s+AUDCHG\b", re.IGNORECASE)
AUD_JOBNAME_RE = re.compile(r"\bAUD_JOBNAME\s+FOR\s+AUDJOB\b", re.IGNORECASE)
AUD_PGM_RE = re.compile(r"\bAUD_PGM\s+FOR\s+AUDPGM\b", re.IGNORECASE)
SUSPICIOUS_SECRET_RE = re.compile(r"(PASSWORD\s*=|PASSWD\s*=|API[_-]?KEY|TOKEN\s*=|SECRET\s*=)", re.IGNORECASE)
EXECUTABLE_RE = re.compile(r"^\s*(DISPLAY|MOVE|PERFORM|CALL|IF|EVALUATE|EXEC\s+SQL|GOBACK|STOP\s+RUN)\b", re.IGNORECASE)
COMMENT_RE = re.compile(r"^\s*\*>")
COMMENT_COL7_RE = re.compile(r"^ {6}\*>")

SQLTABLE_REQUIRED_PATTERNS = [
    (RECORD_STATUS_RE, "RecordStatus for rcdsts"),
    (BEGINNING_TIME_RE, "beginning_time for begtim"),
    (ENDING_TIME_RE, "ending_time for endtim"),
    (TRANSACTION_START_RE, "transaction_start for trxstr"),
    (PERIOD_SYSTEM_TIME_RE, "period system_time (beginning_time, ending_time)"),
    (AUD_USER_RE, "aud_user for audusr"),
    (AUD_CHANGE_RE, "aud_change for audchg"),
    (AUD_JOBNAME_RE, "aud_jobname for audjob"),
    (AUD_PGM_RE, "aud_pgm for audpgm"),
]


def is_skippable(line: str) -> bool:
    s = line.strip()
    if not s:
        return True
    if COMMENT_RE.match(s):
        return True
    return False


def validate_program_structure(text: str, path: Path) -> list[str]:
    errors: list[str] = []
    if not IDENT_RE.search(text):
        errors.append(f"{path}: missing IDENTIFICATION DIVISION")
    if not PROGRAM_ID_RE.search(text):
        errors.append(f"{path}: missing PROGRAM-ID")
    if not PROC_DIV_RE.search(text):
        errors.append(f"{path}: missing PROCEDURE DIVISION")
    return errors


def validate_common(text: str, lines: list[str], path: Path, require_executable: bool) -> list[str]:
    errors: list[str] = []

    if not text.strip():
        return [f"{path}: file is empty"]

    if SUSPICIOUS_SECRET_RE.search(text):
        errors.append(f"{path}: possible hardcoded credential/token pattern detected")

    for line_no, line in enumerate(lines, start=1):
        stripped = line.lstrip()
        if stripped.startswith("*>") and not COMMENT_COL7_RE.match(line):
            errors.append(
                f"{path}:{line_no}: COBOL line comments must start in column 7 (six leading spaces before '*>')"
            )

    if require_executable:
        executable_count = 0
        for line in lines:
            if is_skippable(line):
                continue
            if EXECUTABLE_RE.search(line):
                executable_count += 1

        if executable_count == 0:
            errors.append(f"{path}: no executable COBOL statements detected")

    return errors


def validate_by_type(member_type: str, text: str, path: Path) -> list[str]:
    errors: list[str] = []

    if member_type in {"cblle", "sqlcblle"}:
        errors.extend(validate_program_structure(text, path))
        if not WORKING_STORAGE_RE.search(text):
            errors.append(f"{path}: missing WORKING-STORAGE SECTION")
        if not GOBACK_RE.search(text):
            errors.append(f"{path}: missing GOBACK return path")

    if member_type == "sqlcblle":
        if not SQLCA_RE.search(text):
            errors.append(f"{path}: SQLCBLLE must include EXEC SQL INCLUDE SQLCA END-EXEC")
        if len(EXEC_SQL_RE.findall(text)) < 2:
            errors.append(f"{path}: SQLCBLLE should include SQLCA include and at least one executable SQL statement")
        if not SQLSTATE_CHECK_RE.search(text):
            errors.append(f"{path}: SQLCBLLE should include explicit success SQLSTATE handling")
        if not SQLSTATE_NO_DATA_RE.search(text):
            errors.append(f"{path}: SQLCBLLE should include explicit no-data SQLSTATE handling (02000)")
        if not SQLSTATE_ERROR_BRANCH_RE.search(text):
            errors.append(f"{path}: SQLCBLLE should include explicit error branch handling (for example, WHEN OTHER)")
        if CREATE_TABLE_RE.search(text):
            for pattern, column_label in SQLTABLE_REQUIRED_PATTERNS:
                matches = pattern.findall(text)
                if not matches:
                    errors.append(
                        f"{path}: embedded SQL CREATE TABLE must include standard/audit column '{column_label}'"
                    )
                elif len(matches) > 1:
                    errors.append(
                        f"{path}: embedded SQL CREATE TABLE must not duplicate standard/audit column '{column_label}'"
                    )

    if member_type == "cpy":
        if PROC_DIV_RE.search(text):
            errors.append(f"{path}: CPY copybook must not contain PROCEDURE DIVISION")
        if not re.search(r"^\s*01\s+", text, re.IGNORECASE | re.MULTILINE):
            errors.append(f"{path}: CPY copybook should contain at least one level-01 declaration")

    return errors


def validate_file(member_type: str, path: Path) -> list[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception as ex:
        return [f"{path}: unable to read file ({ex})"]

    lines = text.splitlines()
    errors = validate_common(text, lines, path, require_executable=(member_type != "cpy"))
    errors.extend(validate_by_type(member_type, text, path))
    return errors


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Validate IBM i COBOL source members")
    parser.add_argument("--type", required=True, choices=["cblle", "sqlcblle", "cpy"], help="COBOL member type")
    parser.add_argument("files", nargs="+", help="COBOL source files to validate")
    args = parser.parse_args(argv[1:])

    all_errors: list[str] = []
    for raw in args.files:
        path = Path(raw)
        if not path.exists():
            all_errors.append(f"{path}: file does not exist")
            continue
        all_errors.extend(validate_file(args.type, path))

    if all_errors:
        for error in all_errors:
            print(f"ERROR: {error}")
        return 1

    print(f"OK: all {args.type.upper()} files passed COBOL checks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
