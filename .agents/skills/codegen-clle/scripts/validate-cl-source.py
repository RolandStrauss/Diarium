#!/usr/bin/env python3
"""
Validate CL source generated by codegen-clle.

Usage:
  python validate-cl-source.py --type clle <file1> [file2 ...]
  python validate-cl-source.py --type clp <file1> [file2 ...]
  python validate-cl-source.py --type cl <file1> [file2 ...]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PGM_RE = re.compile(r"^\s*PGM\b", re.IGNORECASE | re.MULTILINE)
ENDPGM_RE = re.compile(r"^\s*ENDPGM\b", re.IGNORECASE | re.MULTILINE)
DCL_RE = re.compile(r"^\s*DCL\b", re.IGNORECASE | re.MULTILINE)
MONMSG_RE = re.compile(r"\bMONMSG\s+MSGID\(CPF0000\)", re.IGNORECASE)
EXECUTABLE_RE = re.compile(r"^\s*(RTVJOBA|SNDPGMMSG|CHGVAR|CALL|SBMJOB|OVRDBF|DLTOVR|RUNSQLSTM|RETURN)\b", re.IGNORECASE)
COMMENT_RE = re.compile(r"^\s*/\*")
LABEL_RE = re.compile(r"^\s*[A-Z0-9_#$@]+:\s*$", re.IGNORECASE)
SUSPICIOUS_SECRET_RE = re.compile(r"(PASSWORD\s*\(|PASSWD\s*\(|API[_-]?KEY|TOKEN\s*=|SECRET\s*=)", re.IGNORECASE)
GOTO_RE = re.compile(r"\bGOTO\b", re.IGNORECASE)
TFRCTL_RE = re.compile(r"\bTFRCTL\b", re.IGNORECASE)
CRASH_SUBR_RE = re.compile(r"\bSUBR\s+SUBR\(CRASH\)", re.IGNORECASE)
RCVMSG_RE = re.compile(r"\bRCVMSG\b", re.IGNORECASE)
ESCAPE_MSG_RE = re.compile(r"\bSNDPGMMSG\b.*\bMSGTYPE\(\*ESCAPE\)", re.IGNORECASE)
ESCAPE_TYPE_RE = re.compile(r"\bMSGTYPE\(\*ESCAPE\)", re.IGNORECASE)
BIF_RE = re.compile(r"%(TRIM|SST|SCAN|PARMS|SWITCH)\b", re.IGNORECASE)


def is_skippable(line: str) -> bool:
    s = line.strip()
    if not s:
        return True
    if COMMENT_RE.match(s):
        return True
    return False


def validate_common(text: str, lines: list[str], path: Path) -> list[str]:
    errors: list[str] = []

    if not text.strip():
        return [f"{path}: file is empty"]

    if not PGM_RE.search(text):
        errors.append(f"{path}: missing PGM statement")
    if not ENDPGM_RE.search(text):
        errors.append(f"{path}: missing ENDPGM statement")

    if SUSPICIOUS_SECRET_RE.search(text):
        errors.append(f"{path}: possible hardcoded credential/token pattern detected")

    executable_count = 0
    for line in lines:
        if is_skippable(line):
            continue
        if LABEL_RE.match(line):
            continue
        if EXECUTABLE_RE.match(line):
            executable_count += 1

    if executable_count == 0:
        errors.append(f"{path}: no executable CL commands detected")

    return errors


def validate_by_type(member_type: str, text: str, path: Path) -> list[str]:
    errors: list[str] = []

    if member_type == "clle":
        if not DCL_RE.search(text):
            errors.append(f"{path}: CLLE should include at least one DCL declaration")
        if not MONMSG_RE.search(text):
            errors.append(f"{path}: CLLE should include MONMSG MSGID(CPF0000) for baseline error handling")
        if GOTO_RE.search(text):
            errors.append(f"{path}: CLLE should avoid GOTO; use structured IF/DO/SELECT flow")
        if TFRCTL_RE.search(text):
            errors.append(f"{path}: CLLE should avoid TFRCTL in modern ILE flow")
        if not BIF_RE.search(text):
            errors.append(f"{path}: CLLE should use at least one modern BIF (%TRIM, %SST, %SCAN, %PARMS, or %SWITCH)")
        if not CRASH_SUBR_RE.search(text):
            errors.append(f"{path}: CLLE should include SUBR SUBR(CRASH) for robust fallback handling")
        if not RCVMSG_RE.search(text):
            errors.append(f"{path}: CLLE CRASH pattern should include RCVMSG to capture joblog context")
        if not (ESCAPE_MSG_RE.search(text) or ("SNDPGMMSG" in text.upper() and ESCAPE_TYPE_RE.search(text))):
            errors.append(f"{path}: CLLE should escalate terminal failure with SNDPGMMSG ... MSGTYPE(*ESCAPE)")

    return errors


def validate_file(member_type: str, path: Path) -> list[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception as ex:
        return [f"{path}: unable to read file ({ex})"]

    lines = text.splitlines()
    errors = validate_common(text, lines, path)
    errors.extend(validate_by_type(member_type, text, path))
    return errors


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Validate IBM i CL source members")
    parser.add_argument("--type", required=True, choices=["clle", "clp", "cl"], help="CL member type")
    parser.add_argument("files", nargs="+", help="CL source files to validate")
    args = parser.parse_args(argv[1:])

    all_errors: list[str] = []
    for raw in args.files:
        path = Path(raw)
        if not path.exists():
            all_errors.append(f"{path}: file does not exist")
            continue
        all_errors.extend(validate_file(args.type, path))

    if all_errors:
        for error in all_errors:
            print(f"ERROR: {error}")
        return 1

    print(f"OK: all {args.type.upper()} files passed CL checks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
